import logging
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from datetime import datetime
from sklearn.preprocessing import MinMaxScaler
from keras.models import Sequential
from keras.layers import LSTM, Dense
import yfinance as yf
from scipy.optimize import minimize

# Set up logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

# Function to validate date input
def validate_date(date_text):
    try:
        datetime.strptime(date_text, '%Y-%m-%d')
        return True
    except ValueError:
        return False

# Function to fetch stock data with retry logic
def fetch_stock_data_with_retry(ticker, start_date, end_date, max_retries=5):
    for attempt in range(max_retries):
        try:
            df = yf.download(ticker, start=start_date, end=end_date)
            if df.empty:
                logging.warning(f"No data available for {ticker}.")
            return df
        except Exception as e:
            logging.error(f"Attempt {attempt + 1}: Error fetching data for {ticker}: {e}")
            if attempt == max_retries - 1:
                raise
            else:
                continue

# Technical indicator functions
def compute_rsi(series, period=14):
    delta = series.diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=period).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=period).mean()
    rs = gain / loss
    rsi = 100 - (100 / (1 + rs))
    return rsi

def compute_macd(series, short_period=12, long_period=26, signal_period=9):
    short_ema = series.ewm(span=short_period, adjust=False).mean()
    long_ema = series.ewm(span=long_period, adjust=False).mean()
    macd = short_ema - long_ema
    signal_line = macd.ewm(span=signal_period, adjust=False).mean()
    return macd, signal_line

def compute_bollinger_bands(series, window=20, num_std_dev=2):
    rolling_mean = series.rolling(window=window).mean()
    rolling_std = series.rolling(window=window).std()
    upper_band = rolling_mean + (rolling_std * num_std_dev)
    lower_band = rolling_mean - (rolling_std * num_std_dev)
    return upper_band, lower_band

def preprocess_data(df):
    scaler = MinMaxScaler()
    df = df[['Close']].copy()  # Make a copy to avoid warnings
    df['Scaled_Close'] = scaler.fit_transform(df[['Close']])

    # Example of adding technical indicators
    df['RSI'] = compute_rsi(df['Close'])
    df['MACD'], df['Signal_Line'] = compute_macd(df['Close'])
    df['Bollinger_Upper'], df['Bollinger_Lower'] = compute_bollinger_bands(df['Close'])

    # Prepare data for LSTM
    sequence_length = 60
    features = ['Scaled_Close', 'RSI', 'MACD', 'Signal_Line', 'Bollinger_Upper', 'Bollinger_Lower']
    X, y = [], []
    for i in range(len(df) - sequence_length):
        X.append(df[features].iloc[i:i+sequence_length].values)
        y.append(df['Scaled_Close'].iloc[i+sequence_length])

    X = np.array(X)
    y = np.array(y)
    X_train, X_test = X[:-100], X[-100:]
    y_train, y_test = y[:-100], y[-100:]

    return X_train, X_test, y_train, y_test, scaler, df

# Function to create LSTM model
def create_lstm_model(input_shape):
    model = Sequential()
    model.add(LSTM(50, activation='relu', input_shape=input_shape, return_sequences=True))
    model.add(LSTM(50, activation='relu'))
    model.add(Dense(1))
    model.compile(optimizer='adam', loss='mean_squared_error')
    return model

# Function to train the LSTM model
def train_model(model, X_train, y_train, X_test, y_test, epochs=10):
    history = model.fit(X_train, y_train, epochs=epochs, validation_data=(X_test, y_test), verbose=1)
    return history

# Function to predict stock prices
def predict_stock_prices(model, X_test, scaler):
    predictions = model.predict(X_test)
    predictions = scaler.inverse_transform(predictions.reshape(-1, 1))
    return predictions.flatten()

# Function to predict future stock prices
def predict_future_prices(model, df, scaler, days):
    sequence_length = 60
    features = ['Scaled_Close', 'RSI', 'MACD', 'Signal_Line', 'Bollinger_Upper', 'Bollinger_Lower']
    last_sequence = df[features].iloc[-sequence_length:].values
    future_predictions = []

    for _ in range(days):
        x_input = np.expand_dims(last_sequence, axis=0)  # Shape: (1, sequence_length, num_features)
        pred = model.predict(x_input)
        future_predictions.append(pred[0, 0])

        # Update last_sequence for next prediction
        new_row = np.zeros((1, len(features)))
        new_row[0, 0] = pred[0, 0]  # Scaled_Close
        # You might want to compute other features here
        last_sequence = np.vstack((last_sequence[1:], new_row))

    # Rescale predictions
    future_predictions = np.array(future_predictions).reshape(-1, 1)
    future_predictions = scaler.inverse_transform(future_predictions)

    return future_predictions.flatten()



# Function to optimize portfolio
def optimize_portfolio(tickers, start_date, end_date):
    # Fetch data for all tickers
    data = {}
    for ticker in tickers:
        df = fetch_stock_data_with_retry(ticker, start_date, end_date)
        if not df.empty:
            data[ticker] = df['Close']

    if len(data) < 2:
        logging.error("Not enough valid tickers for portfolio optimization.")
        return None

    # Calculate returns
    returns = pd.DataFrame(data).pct_change().dropna()

    # Calculate mean returns and covariance
    mean_returns = returns.mean()
    cov_matrix = returns.cov()

    # Function to calculate negative Sharpe Ratio
    def neg_sharpe_ratio(weights, mean_returns, cov_matrix, risk_free_rate=0.01):
        portfolio_return = np.sum(mean_returns * weights) * 252
        portfolio_std_dev = np.sqrt(np.dot(weights.T, np.dot(cov_matrix, weights))) * np.sqrt(252)
        sharpe_ratio = (portfolio_return - risk_free_rate) / portfolio_std_dev
        return -sharpe_ratio

    # Constraints and bounds
    num_assets = len(tickers)
    constraints = ({'type': 'eq', 'fun': lambda x: np.sum(x) - 1})
    bounds = tuple((0, 1) for _ in range(num_assets))

    # Optimization
    result = minimize(neg_sharpe_ratio, num_assets*[1./num_assets], args=(mean_returns, cov_matrix),
                      method='SLSQP', bounds=bounds, constraints=constraints)

    # Prepare results
    weights = result.x
    portfolio_return = np.sum(mean_returns * weights) * 252
    portfolio_std_dev = np.sqrt(np.dot(weights.T, np.dot(cov_matrix, weights))) * np.sqrt(252)
    sharpe_ratio = -result.fun

    return {
        'weights': {ticker: weight for ticker, weight in zip(tickers, weights)},
        'expected_return': portfolio_return,
        'volatility': portfolio_std_dev,
        'sharpe_ratio': sharpe_ratio
    }

# Function to backtest the model
def backtest_model(model, df, scaler, test_size=100):
    X = []
    for i in range(len(df) - 60):
        X.append(df.iloc[i:i+60].drop(columns='Close').values)
    X = np.array(X)

    predictions = model.predict(X[-test_size:])
    predictions = scaler.inverse_transform(predictions.reshape(-1, 1)).flatten()

    actual = df['Close'].iloc[-test_size:]

    results = pd.DataFrame({'Actual': actual, 'Predicted': predictions}, index=actual.index)

    # Calculate metrics
    mse = np.mean((results['Actual'] - results['Predicted'])**2)
    rmse = np.sqrt(mse)
    mae = np.mean(np.abs(results['Actual'] - results['Predicted']))
    mape = np.mean(np.abs((results['Actual'] - results['Predicted']) / results['Actual'])) * 100

    metrics = {
        'MSE': mse,
        'RMSE': rmse,
        'MAE': mae,
        'MAPE': mape
    }

    return results, metrics


